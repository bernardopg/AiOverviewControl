#!/usr/bin/env bash
# Offline contract: the contributor grid is append-only, pinned contributors
# always render, automation accounts never do, and a rerun changes nothing.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$TMP/repo/scripts" "$TMP/repo/docs" "$TMP/bin"
cp "$ROOT/scripts/render-contributors" "$TMP/repo/scripts/"
fail() { echo "FAIL: $*" >&2; exit 1; }

avatar() { printf '<a href="https://github.com/%s" title="%s"><img src="https://avatars.example/%s?v=4&s=112" width="56" height="56" alt="%s" /></a>' "$1" "$1" "$1" "$1"; }
for file in README.md docs/README.pt-BR.md; do
    {
        echo '# Fixture'
        echo '<!-- CONTRIBUTORS:START - generated by scripts/render-contributors -->'
        echo
        avatar maintainer; echo
        avatar anonymized; echo
        avatar claude; echo
        echo
        echo '<!-- CONTRIBUTORS:END -->'
        echo 'tail'
    } > "$TMP/repo/$file"
done

# The API no longer lists "anonymized" (their commits lost the account link)
# or the pinned SkippySteve, and still reports an automation account as a User.
cat > "$TMP/bin/gh" <<'SH'
#!/usr/bin/env bash
case "$*" in
  *contributors*) printf 'maintainer\thttps://github.com/maintainer\thttps://avatars.example/maintainer?v=4\nclaude\thttps://github.com/claude\thttps://avatars.example/claude?v=4\nnewcomer\thttps://github.com/newcomer\thttps://avatars.example/newcomer?v=4\n' ;;
  *users/SkippySteve*) printf 'SkippySteve\thttps://github.com/SkippySteve\thttps://avatars.example/SkippySteve?v=4\n' ;;
  *) echo "unexpected gh call: $*" >&2; exit 1 ;;
esac
SH
chmod +x "$TMP/bin/gh"
export PATH="$TMP/bin:$PATH" GITHUB_REPOSITORY=owner/repo

bash "$TMP/repo/scripts/render-contributors" > /dev/null
for file in README.md docs/README.pt-BR.md; do
    order="$(grep -o 'title="[^"]*"' "$TMP/repo/$file" | cut -d'"' -f2 | paste -sd' ')"
    [ "$order" = "maintainer anonymized newcomer SkippySteve" ] || fail "$file grid: $order"
    grep -qx tail "$TMP/repo/$file" || fail "$file lost the text after the grid"
done
cp "$TMP/repo/README.md" "$TMP/first"
bash "$TMP/repo/scripts/render-contributors" > /dev/null
cmp -s "$TMP/first" "$TMP/repo/README.md" || fail "second render changed the grid"
grep -q 'SkippySteve' "$ROOT/README.md" || fail "README.md no longer credits SkippySteve"
grep -q 'SkippySteve' "$ROOT/docs/README.pt-BR.md" || fail "docs/README.pt-BR.md no longer credits SkippySteve"
echo 'OK: append-only contributor grid, pinned SkippySteve, automation excluded, idempotent'
