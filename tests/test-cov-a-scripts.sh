#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(mktemp -d /tmp/aioc-cov-a.XXXXXX)"
trap 'rm -rf "$TMP"' EXIT
# Isolate every cache and config path so no real user data is read or written.
export HOME="$TMP/home" XDG_CACHE_HOME="$TMP/cache" XDG_CONFIG_HOME="$TMP/config"
mkdir -p "$HOME"

# The stale/invalid arguments fail before writing outside the supplied temp dir.
if "$ROOT/scripts/package-release" v0.0.0 "$TMP/dist" >"$TMP/package.out" 2>&1; then
  echo 'package-release accepted a mismatched tag' >&2
  exit 1
fi
grep -q 'does not match plugin.json' "$TMP/package.out"

# Exercise the full archive, checksum and manifest validation path from HEAD.
"$ROOT/scripts/package-release" "v$(jq -r .version "$ROOT/plugin.json")" "$TMP/dist" >/dev/null
test -s "$TMP/dist/AiOverviewControl-v$(jq -r .version "$ROOT/plugin.json").zip"

# DCO usage and the valid empty-range path.
if "$ROOT/scripts/check-dco" >/dev/null 2>&1; then
  echo 'check-dco accepted missing arguments' >&2
  exit 1
fi
"$ROOT/scripts/check-dco" HEAD HEAD | grep -q '^DCO OK:'
mkdir -p "$TMP/repo"
git -C "$TMP/repo" init -q
git -C "$TMP/repo" config user.name 'Coverage Fixture'
git -C "$TMP/repo" config user.email 'coverage@example.invalid'
git -C "$TMP/repo" -c commit.gpgsign=false commit --allow-empty -qm base
base="$(git -C "$TMP/repo" rev-parse HEAD)"
git -C "$TMP/repo" -c commit.gpgsign=false commit --allow-empty -qm unsigned
if (cd "$TMP/repo" && "$ROOT/scripts/check-dco" "$base" HEAD) >"$TMP/dco.out" 2>&1; then
  echo 'check-dco accepted an unsigned commit' >&2
  exit 1
fi
grep -q 'DCO check failed' "$TMP/dco.out"

# The metadata gate is offline and passes on the repository's own metadata;
# its rejection cases live in tests/test-metadata.sh.
"$ROOT/scripts/check-metadata" | grep -q '^Metadata OK:'

# Render contributors in an isolated checkout with a deterministic gh stub.
mkdir -p "$TMP/render/scripts" "$TMP/render/docs" "$TMP/render/bin"
cp "$ROOT/scripts/render-contributors" "$TMP/render/scripts/"
for readme in "$TMP/render/README.md" "$TMP/render/docs/README.pt-BR.md"; do
  printf 'before\n<!-- CONTRIBUTORS:START - generated by scripts/render-contributors -->\n\n<a href="https://old" title="Old"><img src="old" /></a>\n\n<!-- CONTRIBUTORS:END -->\nafter\n' >"$readme"
done
cat >"$TMP/render/bin/gh" <<'SH'
#!/usr/bin/env bash
case "$*" in
  *repos/*/contributors*) printf 'NewUser\thttps://example.invalid/new\thttps://example.invalid/new.png\nclaude\thttps://example.invalid/claude\thttps://example.invalid/claude.png\n' ;;
  *users/SkippySteve*) printf 'SkippySteve\thttps://github.com/SkippySteve\thttps://example.invalid/steve.png\n' ;;
  *) exit 1 ;;
esac
SH
chmod +x "$TMP/render/bin/gh"
(cd "$TMP/render" && PATH="$TMP/render/bin:$PATH" GITHUB_REPOSITORY=offline/plugin AVATAR_SIZE=32 bash scripts/render-contributors >/dev/null)
grep -q 'title="Old"' "$TMP/render/README.md"
grep -q 'title="NewUser"' "$TMP/render/README.md"
grep -q 'title="SkippySteve"' "$TMP/render/README.md"
! grep -q 'title="claude"' "$TMP/render/README.md"
grep -q 'title="SkippySteve"' "$TMP/render/docs/README.pt-BR.md"

# qmlls-setup's missing-source diagnostic is safe: it exits before touching cache/config.
if "$ROOT/scripts/qmlls-setup" "$TMP/no-shell" >"$TMP/qmlls.out" 2>&1; then
  echo 'qmlls-setup accepted a missing shell directory' >&2
  exit 1
fi
grep -q 'DMS shell dir not found' "$TMP/qmlls.out"

